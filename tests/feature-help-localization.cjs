'use strict';
const assert=require('node:assert/strict');
const {boot}=require('./tutorial-modals.cjs');
const b=boot();
b.run(`
 reset(3);hearts=[{}];holds.push({type:'hazard'});
 featureHelpSeen={wide:false,heart:false,hazard:false};
 globalThis.imageRequests=[];globalThis.cues=[];
 requestExplanationImage=(src,ready)=>imageRequests.push({src,ready});
 playSound=name=>cues.push(name);
 showStageHelp();
`);
const state=()=>b.run('JSON.stringify({state,featureHelpSeen,pendingFeatureHelp,featureHelpImageTicket,featureHelpImageLoading,cameraIntro,runElapsedMs,runStartedAt,stamina,moveCount,heartItems,lives,stageRecords,dailyRecords,playsSinceAd})');
assert.equal(b.run('JSON.stringify(pendingFeatureHelp)'),JSON.stringify(['wide','heart','hazard']));
assert.equal(b.node('featureHelpContent').lang,'ja');
assert(b.node('featureHelpContent').innerHTML.includes('大きなホールド'));
assert(!b.node('featureHelpContent').innerHTML.includes('lang="ja"'));
const pending=state();b.run("setGameLanguage('en');");
assert.equal(state(),pending,'Language must not change pending decode, queue, timing or resources');
assert.equal(b.node('featureHelpContent').lang,'en');
assert.equal(b.node('featureHelpContent#featureHelpTitle').textContent,'Large Hold');
assert.equal(b.node('featureHelpContentp').textContent,'A large hold can support both hands or both feet.');
assert.equal(b.run('imageRequests.length'),1,'Language refresh must not reload the illustration');
assert.equal(b.run('cues.length'),0);
// A failed image still opens translated text. No acknowledgment or time elapses.
b.run('imageRequests[0].ready(null);');assert(b.node('featureHelpDialog').open);
const open=state();b.run("setGameLanguage('ja');setGameLanguage('en');");assert.equal(state(),open);
assert.equal(b.node('featureHelpContent.modal-tap').textContent,'TAP');
b.run('dismissStageHelp();');
assert(b.node('featureHelpContent').innerHTML.includes('Touch it with your body to restore 2 stamina'));
assert.equal(b.node('featureHelpContent').lang,'en');
assert.equal(b.run('imageRequests.length'),2);
const heart=state();b.run("setGameLanguage('ja');");assert.equal(state(),heart);
assert.equal(b.node('featureHelpContent#featureHelpTitle').textContent,'ハート');
assert.equal(b.node('featureHelpContentp').textContent,b.run('GAME_TEXT_JA["feature.heart"]'));
b.run('imageRequests[1].ready(null);dismissStageHelp();');
assert(b.node('featureHelpContent').innerHTML.includes('小さくとがったホールド'));
b.run("setGameLanguage('en');");
assert.equal(b.node('featureHelpContent#featureHelpTitle').textContent,'Small Pointed Hold');
assert.equal(b.node('featureHelpContentp').textContent,'Each new hand or foot placement costs 1 extra stamina');
b.run('imageRequests[2].ready(null);dismissStageHelp();');
assert.equal(b.run('JSON.stringify(featureHelpSeen)'),JSON.stringify({wide:true,heart:true,hazard:true}));
assert.equal(b.run('JSON.stringify(cues)'),JSON.stringify(['move','move','move']));
const ended=state();b.run("setGameLanguage('ja');setGameLanguage('en');");assert.equal(state(),ended);
assert.equal(b.run('imageRequests.length'),3);assert(!b.node('featureHelpDialog').open);
console.log('PASS feature-help localization: wide/heart/hazard queues, live JA/EN refresh during decode and open modal, failure text, unchanged illustrations/resources/timers/sounds/acknowledgment');
